function getRandomEvent() {
  const available = EVENT_POOL.filter(e => !usedEvents.includes(e.name));
  if (available.length === 0) {
    bot.sendMessage(ADMIN_ID, formatMessage(
      '⚠️ ВНИМАНИЕ!',
      `Все события из пула использованы!\nВсего событий: ${EVENT_POOL.length}\nИспользовано: ${usedEvents.length}\n\nТребуется добавить новые события в EVENT_POOL.`
    ));
    usedEvents = [];
    return getRandomEvent();
  }
  const event = available[Math.floor(Math.random() * available.length)];
  usedEvents.push(event.name);
  return event;
}

function scheduleRandomEvent() {
  const delay = EVENT_COOLDOWN; // ИСПРАВЛЕНО: ровно 6 часов, без рандома
  setTimeout(() => {
    const event = getRandomEvent();
    activeEvent = event;
    for (let id in players) {
      const p = players[id];
      const balance = p.demoMode ? safeNumber(p.demoBalance) : safeNumber(p.balance);
      if ((balance > 0 || safeNumber(p.demoBalance) > 0) && (Date.now() - p.lastPassiveTime < 86400000)) {	
        bot.sendMessage(id, formatMessage(
          '🎉 НОВОЕ СОБЫТИЕ!',
          `${event.name}\n${event.desc}\n\n⏳ Длится: ${event.duration / 60000} минут\n📊 Осталось событий в пуле: ${EVENT_POOL.length - usedEvents.length}`
        )).catch(() => {});
      }
    }
    bot.sendMessage(ADMIN_ID, formatMessage(
      '📢 СОБЫТИЕ ЗАПУЩЕНО',
      `${event.name}\n${event.desc}\n⏳ Длится: ${event.duration / 60000} минут\n📊 Осталось событий: ${EVENT_POOL.length - usedEvents.length}/${EVENT_POOL.length}`
    ));
    if (eventTimer) clearTimeout(eventTimer);
    eventTimer = setTimeout(() => {
      activeEvent = null;
      for (let id in players) {
        const p = players[id];
        const balance = p.demoMode ? safeNumber(p.demoBalance) : safeNumber(p.balance);
        if ((balance > 0 || safeNumber(p.demoBalance) > 0) && (Date.now() - p.lastPassiveTime < 86400000)) {
          bot.sendMessage(id, formatMessage(
            '⏰ СОБЫТИЕ ЗАВЕРШЕНО',
            `"${event.name}" завершено!\nСледующее событие скоро начнётся.`
          )).catch(() => {});
        }
      }
      bot.sendMessage(ADMIN_ID, formatMessage(
        '⏰ СОБЫТИЕ ЗАВЕРШЕНО',
        `"${event.name}" завершено.\nОсталось событий: ${EVENT_POOL.length - usedEvents.length}/${EVENT_POOL.length}`
      ));
      scheduleRandomEvent();
    }, event.duration);
    saveData();
  }, delay);
}

