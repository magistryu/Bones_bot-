bot.onText(/\/trade @(\w+) (\d+)/, async (msg, match) => {
  const id = msg.chat.id;
  const targetUsername = match[1];
  const amount = parseInt(match[2]);
  if (isNaN(amount) || amount < 1) {
    bot.sendMessage(id, formatMessage('ТОРГОВЛЯ', '❌ Укажи сумму больше 0.'));
    return;
  }
  const p = getPlayer(id);
  if (!p) return;
  // Находим игрока по username
  let targetId = null;
  for (let pid in players) {
    if (players[pid].username === targetUsername) {
      targetId = pid;
      break;
    }
  }
  if (!targetId) {
    bot.sendMessage(id, formatMessage('ТОРГОВЛЯ', `❌ Игрок @${targetUsername} не найден.`));
    return;
  }
  if (targetId == id) {
    bot.sendMessage(id, formatMessage('ТОРГОВЛЯ', '❌ Нельзя торговать с самим собой.'));
    return;
  }
  const target = players[targetId];
  const balance = p.demoMode ? safeNumber(p.demoBalance) : safeNumber(p.balance);
  if (balance < amount) {
    bot.sendMessage(id, formatMessage('ТОРГОВЛЯ', `❌ Не хватает. У тебя ${balance} дуб.`));
    return;
  }
  // Лимит: 3 перевода в день
  const today = new Date().toDateString();
  if (p.tradeDate !== today) {
    p.tradeToday = 0;
    p.tradeDate = today;
  }
  if (p.tradeToday >= 3) {
    bot.sendMessage(id, formatMessage('ТОРГОВЛЯ', '❌ Ты исчерпал лимит переводов (3/день).'));
    return;
  }
  // Комиссия 5%
  const fee = Math.floor(amount * 0.05);
  const finalAmount = amount - fee;
  // Списываем у отправителя
  if (p.demoMode) {
    p.demoBalance = safeNumber(p.demoBalance) - amount;
  } else {
    p.balance = safeNumber(p.balance) - amount;
  }
  // Зачисляем получателю
  if (target.demoMode) {
    target.demoBalance = safeNumber(target.demoBalance) + finalAmount;
  } else {
    target.balance = safeNumber(target.balance) + finalAmount;
  }
  // Комиссия в банк
  bank.commission = safeNumber(bank.commission) + fee;
  p.tradeToday++;
  addHistory(id, `Перевод @${targetUsername}: ${finalAmount} дуб. (комиссия ${fee})`);
  addBalanceHistory(id, -amount, `Перевод @${targetUsername}`);
  addHistory(targetId, `Получен перевод от @${p.username}: +${finalAmount} дуб.`);
  addBalanceHistory(targetId, finalAmount, `Перевод от @${p.username}`);
  saveData();
  bot.sendMessage(id, formatMessage('ТОРГОВЛЯ', `✅ Перевод ${finalAmount} дуб. @${targetUsername} выполнен.\n📉 Комиссия: ${fee} дуб.`));
  bot.sendMessage(targetId, formatMessage('ТОРГОВЛЯ', `💰 Ты получил ${finalAmount} дуб. от @${p.username}.`));
});

