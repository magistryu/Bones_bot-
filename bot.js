function endTournament() {
  if (!tournaments.active) return;
  tournaments.active = false;
  const sorted = tournaments.players.sort((a, b) => {
    const balA = players[a]?.balance || 0;
    const balB = players[b]?.balance || 0;
    return balB - balA;
  });
  tournaments.results = sorted;
  if (sorted.length > 0) {
    const winnerId = sorted[0];
    const prize = Math.floor(tournaments.prizePool * TOURNAMENT_CONFIG.winnerPercent);
    if (players[winnerId]) {
      if (players[winnerId].demoMode) {
        players[winnerId].demoBalance = safeNumber(players[winnerId].demoBalance) + prize;
      } else {
        players[winnerId].balance = safeNumber(players[winnerId].balance) + prize;
      }
      bot.sendMessage(winnerId, formatMessage('🏆 ПОБЕДА В ТУРНИРЕ!', `Ты получил ${prize} дуб.`));
    }
    if (sorted.length > 1) {
      const secondPrize = Math.floor(tournaments.prizePool * 0.2);
      const secondId = sorted[1];
      if (players[secondId]) {
        if (players[secondId].demoMode) {
          players[secondId].demoBalance = safeNumber(players[secondId].demoBalance) + secondPrize;
        } else {
          players[secondId].balance = safeNumber(players[secondId].balance) + secondPrize;
        }
        bot.sendMessage(secondId, formatMessage('🥈 2-е МЕСТО!', `Ты получил ${secondPrize} дуб.`));
      }
    }
    if (sorted.length > 2) {
      const thirdPrize = Math.floor(tournaments.prizePool * 0.1);
      const thirdId = sorted[2];
      if (players[thirdId]) {
        if (players[thirdId].demoMode) {
          players[thirdId].demoBalance = safeNumber(players[thirdId].demoBalance) + thirdPrize;
        } else {
          players[thirdId].balance = safeNumber(players[thirdId].balance) + thirdPrize;
        }
        bot.sendMessage(thirdId, formatMessage('🥉 3-е МЕСТО!', `Ты получил ${thirdPrize} дуб.`));
      }
    }
    const participationBonus = Math.floor(tournaments.prizePool * 0.02);
    for (let i = 3; i < Math.min(10, sorted.length); i++) {
      const pid = sorted[i];
      if (players[pid]) {
        if (players[pid].demoMode) {
          players[pid].demoBalance = safeNumber(players[pid].demoBalance) + participationBonus;
        } else {
          players[pid].balance = safeNumber(players[pid].balance) + participationBonus;
        }
        bot.sendMessage(pid, formatMessage('🎉 УЧАСТИЕ В ТУРНИРЕ!', `Ты получил ${participationBonus} дуб. за участие.`));
      }
    }
  }
  saveData();
  setTimeout(() => { startTournament(); }, 7 * 86400000);
}

function scheduleTournament() {
  const now = new Date();
  const day = now.getDay();
  const hours = now.getHours();
  const minutes = now.getMinutes();
  const seconds = now.getSeconds();
  const msUntilSunday = ((7 - day) % 7) * 86400000 + (23 - hours) * 3600000 + (59 - minutes) * 60000 + (59 - seconds) * 1000;
  setTimeout(() => {
    startTournament();
    setTimeout(() => {
      endTournament();
      scheduleTournament();
    }, TOURNAMENT_CONFIG.duration);
  }, msUntilSunday);
}

