// ==================== ФОРМАТТЕР СООБЩЕНИЙ (БЕЗ ПОЛОС — ИСПРАВЛЕН) ====================
function formatMessage(title, body, footer = '') {
  const isWin = title.includes('ПОБЕДА') || title.includes('ПОБЕДА!');
  const isLose = title.includes('ПОРАЖЕНИЕ') || title.includes('ПОРАЖЕНИЕ!');
  
  let topLine, bottomLine;
  
  if (isWin) {
    topLine = '✨💰✨💰✨💰✨💰✨';
    bottomLine = '🏆💎🏆💎🏆💎🏆💎🏆';
  } else if (isLose) {
    topLine = '💀🗡️🖤💀🗡️🖤💀🗡️🖤';
    bottomLine = '🌊⚓💀🌊⚓💀🌊⚓💀';
  } else {
    topLine = '🏴‍☠️🏴‍☠️🏴‍☠️🏴‍☠️🏴‍☠️';
    bottomLine = '🏴‍☠️🏴‍☠️🏴‍☠️🏴‍☠️🏴‍☠️';
  }
  
  if (topLine) {
    return `${topLine}\n   ⚓ ${title} ⚓\n${bottomLine}\n\n${body}\n\n${footer ? footer + '\n' : ''}${bottomLine}`;
  } else {
    return `🏴‍☠️ ${title} 🏴‍☠️\n\n${body}\n\n${footer ? footer + '\n' : ''}🏴‍☠️`;
  }
}

