function getFleetBonus(p) {
  if (!p.fleet || !p.fleet.ships) return 0;
  const count = p.fleet.ships.length;
  if (count >= 20) return 100;
  if (count >= 10) return 50;
  if (count >= 5) return 20;
  return 0;
}

function attackFleet(attackerId, defenderId) {
  const attacker = getPlayer(attackerId);
  const defender = getPlayer(defenderId);
  if (!attacker || !defender) return;
  if (defender.fleetProtection && defender.fleetProtection > Date.now()) {
    bot.sendMessage(attackerId, formatMessage('АТАКА', '❌ У игрока активна защита флота.'));
    return;
  }
  const attackChance = Math.random() * 100;
  const success = attackChance < 50;
  const defenderIncome = defender.fleet?.totalIncome || 0;
  const attackerIncome = attacker.fleet?.totalIncome || 0;
  if (success) {
    const stolen = Math.floor(defenderIncome * 0.1);
    if (attacker.demoMode) {
      attacker.demoBalance = safeNumber(attacker.demoBalance) + stolen;
    } else {
      attacker.balance = safeNumber(attacker.balance) + stolen;
    }
    addHistory(attackerId, `Атака на @${defender.username}: успех +${stolen} дуб.`);
    addHistory(defenderId, `Атака от @${attacker.username}: потеряно ${stolen} дуб.`);
    bot.sendMessage(attackerId, formatMessage('⚔️ АТАКА УСПЕШНА!', `💰 +${stolen} дуб. украдено у @${defender.username}.`));
    bot.sendMessage(defenderId, formatMessage('💀 ВАС АТАКОВАЛИ!', `💸 @${attacker.username} украл ${stolen} дуб.`));
  } else {
    const penalty = Math.floor(attackerIncome * 0.05);
    if (attacker.demoMode) {
      attacker.demoBalance = safeNumber(attacker.demoBalance) - penalty;
    } else {
      attacker.balance = safeNumber(attacker.balance) - penalty;
    }
    addHistory(attackerId, `Атака на @${defender.username}: провал -${penalty} дуб.`);
    bot.sendMessage(attackerId, formatMessage('💀 АТАКА ПРОВАЛЕНА!', `💸 Ты потерял ${penalty} дуб.`));
  }
  saveData();
}

function getShipIncome(ship) {
  return Math.floor(ship.income * (1 + ship.level * 0.2));
}

function getShipUpgradeCost(ship) {
  return Math.floor(ship.upgradeCost * (1 + ship.level * 0.3));
}

function calculateTotalIncome(p) {
  if (!p.fleet || !p.fleet.ships) return 0;
  let total = 0;
  for (let s of p.fleet.ships) {
    const ship = SHIPS.find(sh => sh.id === s.id);
    if (ship) {
      total += getShipIncome({ ...ship, level: s.level });
    }
  }
  const bonus = getFleetBonus(p);
  return Math.floor(total * (1 + bonus / 100));
}

function collectPassiveIncome(id) {
  const p = getPlayer(id);
  if (!p) return;
  const now = Date.now();
  const elapsedMs = now - p.lastPassiveTime;
  const hours = elapsedMs / 3600000;
  if (hours < 1) return;
  const basePassive = RANKS[p.rank].passive;
  const bonusMultiplier = 1 + (p.passiveBonus || 0) / 100;
  const earned = Math.floor(basePassive * hours * bonusMultiplier);
  if (earned > 0) {
    p.passiveCollected = safeNumber(p.passiveCollected) + earned;
    p.lastPassiveTime = now;
    saveData();
  }
}

function checkAchievements(id) {
  const p = getPlayer(id);
  if (!p) return;
  const earned = p.achievements || [];
  for (let ach of ACHIEVEMENTS) {
    if (earned.includes(ach.id)) continue;
    let condition = false;
    switch (ach.id) {
      case 1: condition = p.games >= 1; break;
      case 2: condition = p.wins >= 5; break;
      case 3: condition = p.wins >= 10; break;
      case 4: condition = p.wins >= 100; break;
      case 5: condition = safeNumber(p.balance) >= 1000000; break;
      case 6: condition = p.duelStats.wins >= 50; break;
      case 7: condition = (p.fleet?.ships?.length || 0) >= 10; break;
      case 8: condition = (p.chestStats?.opened || 0) >= 100; break;
      case 9: condition = p.games >= 50; break;
      case 10: condition = earned.length >= 9; break;
      case 11: condition = p.games >= 100; break;
      case 12: condition = p.games >= 500; break;
      case 13: condition = p.games >= 1000; break;
      case 14: condition = safeNumber(p.balance) >= 1000000000; break;
      case 15: condition = p.duelStats.wins >= 100; break;
      case 16: condition = (p.fleet?.ships?.length || 0) >= 50; break;
      case 17: condition = (p.chestStats?.opened || 0) >= 500; break;
      case 18: condition = p.games >= 1000; break;
      case 19: condition = earned.length >= 18; break;
    }
    if (condition) {
      earned.push(ach.id);
      p.achievements = earned;
      p.passiveBonus = (p.passiveBonus || 0) + ach.bonusPassive;
      addHistory(id, `🏆 Достижение: ${ach.name} (+${ach.bonusPassive}% к пассивному доходу)`);
      bot.sendMessage(id, formatMessage(
        'ДОСТИЖЕНИЕ РАЗБЛОКИРОВАНО!',
        `${ach.name}\n${ach.desc}\n📈 +${ach.bonusPassive}% к пассивному доходу\n💰 Текущий бонус: ${p.passiveBonus || 0}%`
      ));
      saveData();
    }
  }
}

function getJackpotTarget() {
  return Math.floor(Math.random() * 100) + 1;
}

function getJackpotBar() {
  const target = getJackpotTarget();
  const progress = Math.min(jackpotCounter / target, 1);
  const filled = Math.floor(progress * 20);
  const empty = 20 - filled;
  return '█'.repeat(filled) + '░'.repeat(empty);
}

function checkJackpot(id, betAmount) {
  const p = getPlayer(id);
  if (!p) return 0;
  const percent = 0.5 + Math.random() * 4.5;
  const increment = Math.floor(betAmount * percent / 100);
  if (increment < 1) return 0;
  bank.jackpot = safeNumber(bank.jackpot) + increment;
  jackpotCounter++;
  const target = getJackpotTarget();
  const bar = getJackpotBar();
  if (Math.random() < 0.01) {
    const winAmount = bank.jackpot;
    bank.jackpot = 0;
    const totalWin = betAmount + winAmount;
    if (p.demoMode) {
      p.demoBalance = safeNumber(p.demoBalance) + totalWin;
    } else {
      p.balance = safeNumber(p.balance) + totalWin;
    }
    addHistory(id, `🎰 ДЖЕКПОТ! +${winAmount} дуб. (всего: ${totalWin})`);
    bot.sendMessage(id, formatMessage('🎰 ДЖЕКПОТ ВЫИГРАН!', `💰 +${winAmount} дуб.\n🎉 Поздравляем!`));
    return totalWin;
  }
  return 0;
}

function checkJackpotBonus(id, betAmount, isWin) {
  const p = getPlayer(id);
  if (!p) return;
  if (betAmount >= 1000) {
    checkJackpot(id, betAmount);
  }
  if (isWin && p.wins >= 5 && p.wins % 5 === 0) {
    checkJackpot(id, betAmount);
  }
}

