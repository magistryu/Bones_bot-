function getRandomEvent() {
  const available = EVENT_POOL.filter(e => !usedEvents.includes(e.name));
  if (available.length === 0) {
    bot.sendMessage(ADMIN_ID, formatMessage(
      '⚠️ ВНИМАНИЕ!',
      `Все события из пула использованы!\nВсего событий: ${EVENT_POOL.length}\nИспользовано: ${usedEvents.length}\n\nТребуется добавить новые события в EVENT_POOL.`
    ));
    usedEvents = [];
    return getRandomEvent();
  }
  const event = available[Math.floor(Math.random() * available.length)];
  usedEvents.push(event.name);
  return event;
}

